#!/usr/bin/env node
/* ============================================================
   scripts/generate-old-domain-map.js — regenerates
   netlify/edge-functions/old-domain-map.js from the current
   netlify.toml (childrensministrylessons.com rules) and _redirects
   (extensionless-shadow hub-page rules).

   Run this after editing an old-domain rule in netlify.toml, or
   after _redirects regenerates (node build.js) with a new/changed
   root-page list — the edge function has its own copy of this data
   (see old-domain-redirect.js for why) and does not read either
   file at request time, so it goes stale if you hand-edit one side
   and forget the other.

   No dependencies (matches build.js) — netlify.toml is parsed with
   a plain regex over its [[redirects]] blocks, not a TOML parser.
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, '..');

const toml = fs.readFileSync(path.join(DIR, 'netlify.toml'), 'utf8');
const blockRe = /\[\[redirects\]\]\n(?:  #[^\n]*\n)*  from = "([^"]+)"\n(?:  #[^\n]*\n)*  to = "([^"]+)"\n  status = 301\n  force = true/g;

const mapping = {};
let m;
while ((m = blockRe.exec(toml))) {
  const [, from, to] = m;
  if (!from.includes('www.childrensministrylessons.com/')) continue;
  if (from.endsWith('/*')) continue;
  const p = from.split('www.childrensministrylessons.com')[1];
  if (!p) continue;
  mapping[p] = to;
}

const redirectsTxt = fs.readFileSync(path.join(DIR, '_redirects'), 'utf8');
for (const line of redirectsTxt.split('\n')) {
  const parts = line.trim().split(/\s+/);
  if (parts.length < 3 || parts[2] !== '301') continue;
  const [from, to] = parts;
  if (!(from in mapping)) mapping[from] = 'https://www.glorykidsministry.com' + to;
}
mapping['/'] = 'https://www.glorykidsministry.com/';

const sorted = {};
for (const k of Object.keys(mapping).sort()) sorted[k] = mapping[k];

const lines = [
  "// GENERATED by scripts/generate-old-domain-map.js (run it after editing netlify.toml's",
  "// childrensministrylessons.com rules, or after _redirects regenerates) — keep this in",
  "// sync rather than hand-editing. See old-domain-redirect.js for how it is used.",
  'export default {',
  ...Object.entries(sorted).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  '};',
  ''
];

fs.writeFileSync(path.join(DIR, 'netlify/edge-functions/old-domain-map.js'), lines.join('\n'));
console.log(`Wrote ${Object.keys(sorted).length} old-domain path mappings to netlify/edge-functions/old-domain-map.js`);
