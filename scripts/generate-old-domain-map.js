#!/usr/bin/env node
/* ============================================================
   scripts/generate-old-domain-map.js — regenerates the ENTIRE
   netlify/edge-functions/old-domain-redirect.js file (map + logic
   together, one self-contained file — no relative import between
   edge-function files, since that isn't confirmed-supported by
   Netlify's own docs and this needs to be certain to deploy) from
   the current netlify.toml (childrensministrylessons.com rules)
   and _redirects (extensionless-shadow hub-page rules).

   Run this after editing an old-domain rule in netlify.toml, or
   after _redirects regenerates (node build.js) with a new/changed
   root-page list — the edge function has its own copy of this data
   and does not read either file at request time, so it goes stale
   if you hand-edit one side and forget the other.

   No dependencies (matches build.js) — netlify.toml is parsed with
   a plain regex over its [[redirects]] blocks, not a TOML parser.
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');
const DIR = path.join(__dirname, '..');

const toml = fs.readFileSync(path.join(DIR, 'netlify.toml'), 'utf8');
const blockRe = /\[\[redirects\]\]\n(?:  #[^\n]*\n)*  from = "([^"]+)"\n(?:  #[^\n]*\n)*  to = "([^"]+)"\n  status = 301\n  force = true/g;

const mapping = {};
let m;
while ((m = blockRe.exec(toml))) {
  const [, from, to] = m;
  if (!from.includes('www.childrensministrylessons.com/')) continue;
  if (from.endsWith('/*')) continue;
  const p = from.split('www.childrensministrylessons.com')[1];
  if (!p) continue;
  mapping[p] = to;
}

const redirectsTxt = fs.readFileSync(path.join(DIR, '_redirects'), 'utf8');
for (const line of redirectsTxt.split('\n')) {
  const parts = line.trim().split(/\s+/);
  if (parts.length < 3 || parts[2] !== '301') continue;
  const [from, to] = parts;
  if (!(from in mapping)) mapping[from] = 'https://www.glorykidsministry.com' + to;
}
mapping['/'] = 'https://www.glorykidsministry.com/';

const sorted = {};
for (const k of Object.keys(mapping).sort()) sorted[k] = mapping[k];

const mapEntries = Object.entries(sorted).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');

const out = `/* ============================================================
   old-domain-redirect.js — Netlify Edge Function

   GENERATED by scripts/generate-old-domain-map.js — re-run it after
   editing an old-domain rule in netlify.toml, or after _redirects
   regenerates (node build.js) with a new/changed root-page list; do
   not hand-edit OLD_DOMAIN_MAP below, it will be overwritten.

   Forces every childrensministrylessons.com (apex or www) request to
   a single 301 straight to its final URL on
   https://www.glorykidsministry.com.

   WHY an edge function and not just _redirects/netlify.toml: Netlify's
   own clean-URL file resolution (try "<path>.html", "<path>/index.html")
   runs ahead of the redirects engine for ANY extensionless path that
   resolves to a real file — confirmed live, this bypasses even a
   force=true wildcard rule. A bare old-domain hit like /blog or
   /free-bible-lessons was coming back 200 (served directly) instead of
   redirecting, because this site's own blog.html / free-bible-lessons.html
   happen to also "exist" at that resolved path. Edge Functions run
   earlier in the request pipeline than that file-resolution step, so
   this is not subject to the same precedence bug.

   The map is inlined in this one file (not a separate imported module)
   so there is no relative-import behavior between edge-function files
   to depend on — Netlify's docs don't explicitly confirm that is
   supported, and this needs to be certain to deploy.

   OLD_DOMAIN_MAP has ${Object.keys(sorted).length} entries: 101 old-slug (lesson/blog/collection)
   mappings + 19 bare hub-page paths (/blog, /about, /free-bible-lessons,
   etc. — the same extensionless-shadow list build.js writes to
   _redirects for the primary domain) − 2 that appear in both lists
   (/free-bible-lessons, /contact), giving ${Object.keys(sorted).length} unique paths.
   ============================================================ */
const NEW_ORIGIN = 'https://www.glorykidsministry.com';
const OLD_HOSTS = new Set([
  'childrensministrylessons.com',
  'www.childrensministrylessons.com',
]);

const OLD_DOMAIN_MAP = {
${mapEntries}
};

export default async (request, context) => {
  // Fail OPEN: this runs on every request to the site (config.path is "/*"),
  // so any bug here — a bad URL, a lookup throwing — must fall through to
  // the normal site instead of ever breaking glorykidsministry.com.
  try {
    const url = new URL(request.url);

    // Never touches glorykidsministry.com (or anything else) — the only
    // domains this ever acts on are the two old-domain hosts above.
    if (!OLD_HOSTS.has(url.hostname)) {
      return context.next();
    }

    // Normalize ONLY for the map lookup (never the fallback target, which
    // keeps whatever the visitor actually requested): strip one trailing
    // slash so "/blog/" matches the same entry as "/blog", then fall back
    // to a lowercase match so "/About" or "/BLOG" still hits the map.
    let lookupPath = url.pathname;
    if (lookupPath.length > 1 && lookupPath.endsWith('/')) lookupPath = lookupPath.slice(0, -1);
    const mapped = OLD_DOMAIN_MAP[lookupPath] || OLD_DOMAIN_MAP[lookupPath.toLowerCase()];

    // Covers every old-domain request, mapped or not: a known old slug/hub
    // goes to its specific new page; anything else (a made-up path, an
    // asset, a trailing-slash or capitalization variant not in the map)
    // still gets exactly one 301, to the same path on the new domain.
    // url.search is appended in both branches so a query string always
    // survives the redirect.
    const target = mapped
      ? (mapped.includes('?') ? mapped : mapped + url.search)
      : (NEW_ORIGIN + url.pathname + url.search);

    return new Response(null, {
      status: 301,
      headers: { Location: target },
    });
  } catch (e) {
    return context.next();
  }
};

export const config = { path: '/*' };
`;

fs.writeFileSync(path.join(DIR, 'netlify/edge-functions/old-domain-redirect.js'), out);
fs.rmSync(path.join(DIR, 'netlify/edge-functions/old-domain-map.js'), { force: true });
console.log(`Wrote ${Object.keys(sorted).length} old-domain path mappings into old-domain-redirect.js (single self-contained file).`);
